/**
 * CKEditor 48 ships CSS separately from the JS modules. TYPO3 core compiles
 * ckeditor5/dist/ckeditor5.css (+ a few TYPO3 rules) into EXT:rte_ckeditor/Resources/Public/Css/editor.css.
 * The extension renders its own editor element (it does not call core's render()), and it ships
 * premium packages core does not have, so it builds its own stylesheet:
 *
 *   Contrib/ckeditor5.css = ckeditor5/dist/ckeditor5.css           (all open-source packages, as core)
 *                         + dist/index.css of every shipped package that is not part of the umbrella (premium)
 *                         + TYPO3 core's additions from Build/Sources/Sass/ckeditor5.scss
 *
 * Loaded by Classes/Form/Element/CustomAssetTrait.php (TYPO3 13/14 only), instead of core's editor.css,
 * so the CKEditor CSS always matches the bundled JS version.
 */
import fs from 'node:fs';
import path from 'node:path';
import postcss from 'postcss';
import cssnano from 'cssnano';

const outDir = path.resolve(process.env.CONTRIB_OUT_DIR || '../../Resources/Public/Contrib');
const { core, extras } = JSON.parse(fs.readFileSync('./packages.json', 'utf8'));
const umbrella = JSON.parse(fs.readFileSync('node_modules/ckeditor5/package.json', 'utf8'));
const inUmbrella = new Set(Object.keys(umbrella.dependencies || {}));

const parts = [{ name: 'ckeditor5', file: 'node_modules/ckeditor5/dist/ckeditor5.css' }];
for (const pkg of [...core, ...extras]) {
  if (inUmbrella.has(pkg)) continue;
  const file = `node_modules/${pkg}/dist/index.css`;
  if (fs.existsSync(file)) parts.push({ name: pkg, file });
}

// Same additions as TYPO3 core 13.4/14.3 Build/Sources/Sass/ckeditor5.scss
const typo3 = `
.ck.ck-content * { user-select: auto !important; }
.ck.ck-linktext { max-width: 300px; overflow: hidden; align-items: center; white-space: nowrap; text-overflow: ellipsis; user-select: none; border: 1px solid transparent !important; line-height: var(--ck-ui-component-min-height) !important; }
.ck.ck-word-count { margin-top: .5rem; }
.ck.ck-softhyphen { color: #0078e6; background-color: rgba(0, 120, 230, .1); padding-left: .1em; padding-right: .1em; }
.ck.ck-nbsp { color: #c83c3c; background-color: rgba(200, 60, 60, .1); padding-left: .1em; padding-right: .1em; }
`;

const source = parts.map(p => fs.readFileSync(p.file, 'utf8')).join('\n') + typo3;
const { css } = await postcss([cssnano({ preset: 'default' })]).process(source, { from: undefined });
const banner = `/*! CKEditor 5 ${umbrella.version} styles for EXT:rte_ckeditor_pack (generated by Build/ckeditor/build-css.mjs). Sources: ${parts.map(p => p.name).join(', ')}. CKEditor 5 is licensed under GPL-2.0-or-later or a commercial license, see https://ckeditor.com/legal/ckeditor-licensing-options */\n`;
fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(path.join(outDir, 'ckeditor5.css'), banner + css + '\n');
console.log(`ckeditor5.css: ${parts.length} sources, ${(css.length / 1024).toFixed(0)} KiB`);
